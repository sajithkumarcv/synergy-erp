CREATE   TRIGGER proj.TR_POLine_RecalcStatus
ON proj.TBL_PURCHASE_ORDER_LINE
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT (UPDATE(ReceivedQty) OR UPDATE(OrderedQty)) RETURN;
    IF TRIGGER_NESTLEVEL(OBJECT_ID('proj.TR_POLine_RecalcStatus')) > 1 RETURN;

    -- 1. Recompute LineStatus for the changed lines.
    UPDATE pol
    SET    pol.LineStatus = CASE WHEN ISNULL(pol.ReceivedQty,0) <= 0 THEN 'Open'
                                 WHEN ISNULL(pol.ReceivedQty,0) >= pol.OrderedQty THEN 'Received'
                                 ELSE 'Partial' END
    FROM   proj.TBL_PURCHASE_ORDER_LINE pol
    JOIN   inserted i ON i.PoLineId = pol.PoLineId
    WHERE  pol.LineStatus NOT IN ('Closed','Cancelled');

    -- 2. Roll the header up/down for the affected POs.
    UPDATE po
    SET    po.Status = CASE
               WHEN NOT EXISTS (SELECT 1 FROM proj.TBL_PURCHASE_ORDER_LINE l
                                WHERE l.PoId = po.PoId AND l.IsActive = 1
                                  AND l.LineStatus NOT IN ('Received','Closed','Cancelled'))
                    AND EXISTS (SELECT 1 FROM proj.TBL_PURCHASE_ORDER_LINE l
                                WHERE l.PoId = po.PoId AND l.IsActive = 1
                                  AND l.LineStatus = 'Received') THEN 'Received'
               WHEN EXISTS (SELECT 1 FROM proj.TBL_PURCHASE_ORDER_LINE l
                            WHERE l.PoId = po.PoId AND l.IsActive = 1
                              AND ISNULL(l.ReceivedQty,0) > 0) THEN 'Partial'
               -- nothing received anymore -> revert (reversal procs may override to 'Sent')
               WHEN po.Status IN ('Partial','Received') THEN 'Approved'
               ELSE po.Status END,
           po.ModifiedDate = GETDATE()
    FROM   proj.TBL_PURCHASE_ORDER po
    WHERE  po.PoId IN (SELECT DISTINCT PoId FROM inserted)
      AND  po.Status NOT IN ('Cancelled','Closed','Draft','Hold');
END
GO

CREATE   TRIGGER proj.TR_PRLine_RecalcStatus
ON proj.TBL_PURCHASE_REQUEST_LINE
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT UPDATE(PoCreatedQty) RETURN;
    IF TRIGGER_NESTLEVEL(OBJECT_ID('proj.TR_PRLine_RecalcStatus')) > 1 RETURN;

    -- 1. Recompute the changed PR lines.
    UPDATE prl
    SET    prl.LineStatus = CASE
               WHEN ISNULL(prl.PoCreatedQty,0) >= prl.RequiredQty AND prl.RequiredQty > 0 THEN 'Ordered'
               WHEN ISNULL(prl.PoCreatedQty,0)  > 0                                        THEN 'Partial'
               ELSE 'Open' END
    FROM   proj.TBL_PURCHASE_REQUEST_LINE prl
    JOIN   inserted i ON i.PrLineId = prl.PrLineId
    WHERE  prl.LineStatus NOT IN ('Closed','Cancelled');

    -- 2. Roll the PR header up.
    UPDATE pr
    SET    pr.Status = CASE
               WHEN NOT EXISTS (SELECT 1 FROM proj.TBL_PURCHASE_REQUEST_LINE l
                                WHERE l.PrId = pr.PrId AND l.IsActive = 1
                                  AND l.LineStatus NOT IN ('Ordered','Closed','Cancelled'))
                    AND EXISTS (SELECT 1 FROM proj.TBL_PURCHASE_REQUEST_LINE l
                                WHERE l.PrId = pr.PrId AND l.IsActive = 1
                                  AND l.LineStatus = 'Ordered') THEN 'Ordered'
               WHEN EXISTS (SELECT 1 FROM proj.TBL_PURCHASE_REQUEST_LINE l
                            WHERE l.PrId = pr.PrId AND l.IsActive = 1
                              AND ISNULL(l.PoCreatedQty,0) > 0) THEN 'Partial'
               WHEN pr.Status IN ('Partial','Ordered') THEN 'Approved'
               ELSE pr.Status END,
           pr.ModifiedDate = GETDATE()
    FROM   proj.TBL_PURCHASE_REQUEST pr
    WHERE  pr.PrId IN (SELECT DISTINCT PrId FROM inserted)
      AND  pr.Status NOT IN ('Draft','Cancelled','Closed','Rejected');
END
GO

CREATE TRIGGER TRG_single_base_currency
ON PROJ.TBL_CURRENCY
AFTER INSERT, UPDATE
AS
BEGIN
    IF EXISTS (SELECT 1 FROM inserted WHERE IsBaseCurrency = 1)
    BEGIN
        -- Demote old base currency: reset flag AND exchange rate
        UPDATE TBL_CURRENCY
        SET IsBaseCurrency = 0,
            ExchangeRate    = 1.000000,  -- reset old base rate to 1
            ModifiedDate       = GETDATE()
        WHERE IsBaseCurrency = 1
          AND CurrencyId NOT IN (SELECT CurrencyId FROM inserted);

        -- Ensure the NEW base currency also has exchange_rate = 1
        UPDATE TBL_CURRENCY
        SET ExchangeRate = 1.000000,
            ModifiedDate    = GETDATE()
        WHERE CurrencyId IN (SELECT CurrencyId FROM inserted WHERE IsBaseCurrency = 1);
    END
END;
