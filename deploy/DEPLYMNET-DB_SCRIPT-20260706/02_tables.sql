CREATE   TRIGGER proj.TR_BOM_RecalcStatus
ON proj.TBL_BOM_DETAILS
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT (UPDATE(PoCreatedQty) OR UPDATE(PrCreatedQty) OR UPDATE(BomReceivedQty)) RETURN;
    IF TRIGGER_NESTLEVEL(OBJECT_ID('proj.TR_BOM_RecalcStatus')) > 1 RETURN;

    UPDATE bom
    SET    bom.BomStatus = CASE
               WHEN ISNULL(bom.BomReceivedQty,0) >= bom.BomRequestedQty THEN 'FullyReceived'
               WHEN ISNULL(bom.BomReceivedQty,0)  > 0                   THEN 'PartialReceived'
               WHEN ISNULL(bom.PoCreatedQty,0)   >= bom.BomRequestedQty THEN 'PORaised'
               WHEN ISNULL(bom.PoCreatedQty,0)    > 0                   THEN 'POPartial'
               WHEN ISNULL(bom.PrCreatedQty,0)   >= bom.BomRequestedQty THEN 'PRRaised'
               WHEN ISNULL(bom.PrCreatedQty,0)    > 0                   THEN 'PRPartial'
               ELSE 'Pending' END,
           bom.ModifiedDate = GETDATE()
    FROM   proj.TBL_BOM_DETAILS bom
    JOIN   inserted i ON i.BomId = bom.BomId;
END
GO


